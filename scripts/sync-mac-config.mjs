#!/usr/bin/env node
/**
 * Writes `apps/mac/Config/Config.xcconfig` — the URLs the Swift app talks to.
 *
 * Gitignored and regenerated per build, with localhost defaults so a fresh
 * clone runs against `pnpm dev` with no setup. check-release-env.mjs refuses
 * to ship a build whose values still point at localhost.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const target = join(root, "apps", "mac", "Config", "Config.xcconfig");

function fromEnvFile() {
  try {
    const text = readFileSync(join(root, ".env"), "utf8");
    return Object.fromEntries(
      text
        .split("\n")
        .map((line) => /^\s*([A-Z][A-Z0-9_]*)\s*=\s*(.*)\s*$/.exec(line))
        .filter((m) => m !== null)
        .map((m) => [m[1], m[2].replace(/^["']|["']$/g, "")]),
    );
  } catch {
    return {};
  }
}

const file = fromEnvFile();
const pick = (key, fallback) => process.env[key] || file[key] || fallback;

const values = {
  NM_API_URL: pick("NEXT_PUBLIC_API_URL", "http://localhost:8787"),
  NM_APP_URL: pick("NEXT_PUBLIC_APP_URL", "http://localhost:3000"),
  NM_ASSETS_URL: pick("NEXT_PUBLIC_ASSETS_URL", "http://localhost:8787"),
};

// xcconfig treats `//` as a comment, including inside a value — so a bare
// https://example.com silently becomes "https:". `$()` is an empty variable
// expansion that breaks up the pair without appearing in the output.
const escape = (value) => value.replace("//", "/$()/");

const body = Object.entries(values)
  .map(([key, value]) => `${key} = ${escape(value)}`)
  .join("\n");

writeFileSync(
  target,
  `// Generated by scripts/sync-mac-config.mjs. Gitignored — do not commit.\n` +
    `//\n` +
    `// '//' starts a comment in an xcconfig, including mid-value, so each URL\n` +
    `// has an empty $() expansion inserted between the slashes.\n` +
    `${body}\n`,
);

console.log(`Config.xcconfig -> ${values.NM_API_URL}`);
