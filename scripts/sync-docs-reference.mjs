#!/usr/bin/env node
// Vendors the connector reference material into the website, as one generated
// TypeScript module.
//
// `/docs/llms.txt` hands a model the manifest schema and the runtime contract
// so it can write a connector that registers first time. Both already exist in
// this repository, generated or source, and retyping either into prose would
// produce the one piece of documentation that confidently describes a shape
// the app stopped accepting.
//
// Vendored rather than read at build time, which is what this started as. Next
// traces a `node:fs` path statically, so reading from the repository root made
// Turbopack try to enumerate the whole tree, and it panicked on a dangling
// symlink inside `apps/mac/build/DerivedData`. A generated module has no path
// to trace, and it is the pattern `sync-connector-icons.mjs` already uses.
//
// Run after `pnpm contracts`, and commit the result.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "apps/web/src/lib/docs-reference.generated.ts");

const SOURCES = [
  {
    name: "MANIFEST_SCHEMA",
    path: "contracts/jsonschema/LocalConnectorManifest.json",
    doc: "The JSON Schema a connector manifest is validated against, emitted from `packages/core` by `pnpm contracts`.",
  },
  {
    name: "EXAMPLE_MANIFEST",
    path: "contracts/fixtures/connector-manifest.json",
    doc: "The committed fixture the Mac app's own contract tests decode.",
  },
  {
    name: "AUTHORING_API",
    path: "packages/core/src/define.ts",
    doc: "createApp and createMetric: what an author actually writes.",
  },
  {
    name: "RUNTIME_CONTRACT",
    path: "packages/core/src/runtime.ts",
    doc: "The context object the runner supplies to verify and to each metric's fetch.",
  },
];

/** A TypeScript template literal that cannot be broken by its own contents. */
function literal(text) {
  return `\`${text.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${")}\``;
}

const parts = [
  "// Generated by scripts/sync-docs-reference.mjs. Do not edit.",
  "//",
  "// Run `pnpm docs:reference` after changing the connector contract. The",
  "// sources are listed in that script; each is read verbatim.",
  "",
];

for (const source of SOURCES) {
  const text = readFileSync(join(ROOT, source.path), "utf8").trim();
  parts.push(`/** ${source.doc} */`, `/** Source: \`${source.path}\` */`);
  parts.push(`export const ${source.name} = ${literal(text)};`, "");
}

writeFileSync(OUT, parts.join("\n"));

for (const source of SOURCES) {
  const bytes = readFileSync(join(ROOT, source.path), "utf8").length;
  console.log(`${source.name}: ${bytes} bytes from ${source.path}`);
}
