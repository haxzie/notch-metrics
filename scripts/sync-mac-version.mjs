#!/usr/bin/env node
/**
 * Turns `apps/mac/package.json#version` into `apps/mac/Config/Version.xcconfig`.
 *
 * That package.json is a version-only shim whose sole purpose is to participate
 * in the changesets workspace, which is how a Swift app gets versioned by the
 * same mechanism as the TypeScript packages.
 *
 * The output is **committed**, not gitignored: it means `xcodebuild` works on a
 * fresh clone with no Node step, and it is the reviewable artefact tying a
 * changeset to a Mac release. CI runs this with `--check`.
 */
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const target = join(root, "apps", "mac", "Config", "Version.xcconfig");
const check = process.argv.includes("--check");

const { version } = JSON.parse(readFileSync(join(root, "apps", "mac", "package.json"), "utf8"));

/**
 * The build number. Must be a monotonically increasing integer, and must never
 * be derived from the semver string — a pre-release suffix has nowhere to go.
 *
 * `GITHUB_RUN_NUMBER` in CI, commit count locally. The commit count needs
 * `fetch-depth: 0` wherever it runs or it is wrong *and plausible*, and it
 * decreases under a force push — which is why release-mac.yml asserts the new
 * build is greater than the published one rather than trusting this.
 */
function buildNumber() {
  if (process.env.GITHUB_RUN_NUMBER) return process.env.GITHUB_RUN_NUMBER;
  try {
    return execFileSync("git", ["rev-list", "--count", "HEAD"], { cwd: root }).toString().trim();
  } catch {
    return "1";
  }
}

const contents = `// Generated by scripts/sync-mac-version.mjs. Do not edit — edit the changeset.
//
// Info.plist reads these through $(MARKETING_VERSION) and
// $(CURRENT_PROJECT_VERSION). Do not also set either under
// targets.*.settings in project.yml: a target build setting *overrides* an
// xcconfig value, so the app would ship a stale literal with this file sitting
// right here looking correct.
MARKETING_VERSION = ${version}
CURRENT_PROJECT_VERSION = ${buildNumber()}
`;

const existing = (() => {
  try {
    return readFileSync(target, "utf8");
  } catch {
    return null;
  }
})();

if (check) {
  // Compare only the marketing version. The build number legitimately differs
  // between a local run and CI, and failing on that would make the check fire
  // on every pull request for no reason.
  const want = `MARKETING_VERSION = ${version}`;
  if (existing?.includes(want)) {
    console.log(`Version.xcconfig is up to date (${version})`);
    process.exit(0);
  }
  console.error(
    `::error::apps/mac/Config/Version.xcconfig does not match apps/mac/package.json (${version}).\n` +
      `Run: node scripts/sync-mac-version.mjs`,
  );
  process.exit(1);
}

writeFileSync(target, contents);
console.log(`Version.xcconfig -> ${version} (build ${buildNumber()})`);
