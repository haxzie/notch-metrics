import Foundation
import MetricsAPI
import MetricsCore
import Providers

/// A connection made on this Mac, in the shape the rest of the app already
/// reads.
///
/// `Integration` is what the connections pane, the account picker and the
/// alert centre are all written against, and a second shape beside it would
/// mean a second code path through every one of them. So a local connection
/// is projected into it rather than given a type of its own — the same move
/// `LocalCatalogue` makes for custom apps.
extension LocalConnection {
    var asIntegration: Integration {
        Integration(
            id: id,
            provider: provider,
            label: label,
            // Always healthy. The server tracks `auth_failed` across polls
            // because it is the one doing them; here a bad key shows up on
            // the tile that asked, and there is no sweep to record it
            // against the connection. Claiming a status this app does not
            // maintain would be worse than claiming none.
            status: "ok",
            // Never the key, and never enough of it to be one. The real hint
            // is computed from the credential, which is in the Keychain and
            // deliberately not read to draw a list.
            credentialHint: "Stored on this Mac",
            accountLabel: label,
            accountCurrency: currency,
            // Everything the provider offers, less what this credential
            // cannot reach — a restricted Stripe key reads charges and not
            // subscriptions, and `verify` recorded which.
            enabledMetrics: [],
            availableMetrics: [],
            lastSyncedAt: nil,
            lastErrorAt: nil,
            lastErrorCode: nil,
            createdAt: ISO8601DateFormatter().string(from: connectedAt))
    }

    /// Whether this credential can answer a given metric.
    func canAnswer(_ metric: String) -> Bool { !unavailableMetrics.contains(metric) }
}

extension AppEnvironment {
    /// The catalogue compiled into the app, decoded once.
    ///
    /// Generated by `pnpm catalogue` from the same manifests the adapters
    /// were ported from, so the fields a form asks for and the code that
    /// sends them cannot drift — they are built from one source in one
    /// commit.
    ///
    /// A failure here is a build problem, not a runtime one: the resource is
    /// committed and `mac.sh gen` regenerates it. Reported as an empty
    /// catalogue rather than a crash, because an Integrations pane that says
    /// nothing is better than a notch that will not launch.
    static let bundledCatalogue: ConnectorCatalogue = {
        guard let url = Bundle.main.url(forResource: "catalogue", withExtension: "json"),
              let data = try? Data(contentsOf: url),
              let decoded = try? JSONDecoder().decode(ConnectorCatalogue.self, from: data)
        else {
            return ConnectorCatalogue(version: "missing", categories: [])
        }
        return decoded
    }()

    // MARK: - Reading

    /// Every connection the app knows about.
    ///
    /// Only the ones made on this Mac. The server used to hold half of this
    /// list; it no longer holds any of it, and nothing here asks. A
    /// connection is a row in `settings.json` and a key in the Keychain, and
    /// that is the whole of it.
    var allConnections: [Integration] {
        settings.localConnections.map(\.asIntegration)
    }

    func connections(for provider: String) -> [Integration] {
        allConnections.filter { $0.provider == provider }
    }

    /// Whether this id names a connection this app still knows about.
    ///
    /// False for the `int_…` ids left behind by connections the server used
    /// to hold. Those rows are gone and their credentials were never
    /// readable from here, so a widget still bound to one has to be pointed
    /// at a connection made in the notch.
    func isLocalConnection(_ id: String) -> Bool {
        settings.localConnections.contains { $0.id == id }
    }

    func localConnection(_ id: String) -> LocalConnection? {
        settings.localConnections.first { $0.id == id }
    }

    /// The catalogue, with this Mac's connections folded in.
    ///
    /// The one place a catalogue is obtained, so every view sees the same
    /// accounts. Read from the app bundle rather than from the network: a
    /// connector's fields and setup steps are static data compiled from the
    /// same manifests the adapters were ported from, and asking a server for
    /// them would put a round trip in front of a form whose whole point is
    /// that it needs none.
    func catalogue() async throws(APIError) -> ConnectorCatalogue {
        let served = Self.bundledCatalogue
        let mine = Dictionary(grouping: settings.localConnections, by: \.provider)
        guard !mine.isEmpty else { return served }

        return ConnectorCatalogue(
            version: served.version,
            categories: served.categories.map { group in
                ConnectorCategoryGroup(
                    id: group.id, label: group.label,
                    connectors: group.connectors.map { entry in
                        guard let local = mine[entry.id] else { return entry }
                        return entry.withConnections(
                            local.map {
                                ConnectorConnection(id: $0.id, label: $0.label, status: "ok")
                            } + entry.connections)
                    })
            })
    }

    // MARK: - Writing

    /// Renames a connection.
    ///
    /// Returns the failure rather than presenting it, so the pane can put the
    /// message beside the row that caused it — nil when it worked. Nothing
    /// can fail here today; the signature is kept because the pane's call
    /// site reads the same either way and a future rename may validate.
    func renameConnection(_ id: String, to label: String) async -> String? {
        let trimmed = label.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.isEmpty else { return nil }

        updateSettings { settings in
            guard let index = settings.localConnections.firstIndex(where: { $0.id == id })
            else { return }
            settings.localConnections[index].label = trimmed
        }
        catalogueChanged()
        return nil
    }

    /// Disconnects, and takes the key with it.
    ///
    /// There is no server-side row to revoke any more, so this is the only
    /// thing that removes the credential: a settings entry deleted without
    /// wiping the Keychain would leave somebody's Stripe key on disk with
    /// nothing in the app pointing at it or able to remove it.
    func disconnect(_ id: String) async -> String? {
        guard let connection = localConnection(id) else { return nil }
        removeConnection(connection)
        return nil
    }
}
