import {
  AUTHORING_API,
  EXAMPLE_MANIFEST,
  MANIFEST_SCHEMA,
  RUNTIME_CONTRACT,
} from "@/lib/docs-reference.generated";
import { allDocs, SECTION_LABELS } from "@/lib/docs";
import { SITE_URL, absoluteUrl } from "@/lib/site";

/**
 * `/docs/llms.txt`: one file an agent reads before writing a connector.
 *
 * The site already serves `/llms.txt` and `/llms-full.txt`, and this is
 * neither. Those two are a retrieval corpus for an assistant answering a
 * question about the product. This one is a working specification handed to
 * a model that is about to write a file somebody will run on their Mac, so
 * it carries the things prose cannot carry safely: the JSON Schema for the
 * manifest, the exact TypeScript of the runtime contract, and a complete
 * example that would pass registration.
 *
 * The schema and the contract are **vendored, never retyped**. Both are
 * generated or source files elsewhere in this repository, copied in by
 * `pnpm docs:reference`, so a field added to the connector format appears
 * here with no prose edit. A hand-written copy of either would be the one
 * piece of documentation that confidently describes a shape the app stopped
 * accepting.
 *
 * Vendored rather than read with `node:fs` at build time, which is what this
 * was first. Next traces an `fs` path statically, so reading from the
 * repository root made Turbopack enumerate the whole tree and panic on a
 * dangling symlink under `apps/mac/build`.
 */

/**
 * The prompt the docs index offers to copy.
 *
 * Short on purpose. Its whole job is to get the model to fetch the bundle,
 * so everything it could say about the format is a sentence that will be out
 * of date before the bundle it is pointing at.
 */
export const BUILD_PROMPT = `Read ${SITE_URL}/docs/llms.txt and follow it.

I want to build a Notch Metrics custom app: a local connector that reads an API I use and shows the numbers as widgets in my MacBook notch.

Before writing anything, ask me which API, which numbers I want, and how I authenticate to it. Then write the connector directory and tell me how to load it.

Rules that file sets, and that you must keep:
- Network access goes through ctx.http, never a bare fetch.
- Every host the connector reaches is declared in allowedHosts.
- The code runs on my Mac as me. It is contained by the host allowlist, it is not a sandbox, so do not write anything you would not run yourself.`;

function sectionHeading(label: string): string[] {
  return ["", "---", "", `# ${label}`, ""];
}

export function docsBundle(): string {
  const docs = allDocs().filter((doc) => !doc.draft);

  const parts: string[] = [
    "# Notch Metrics: custom apps and widgets",
    "",
    "> Everything needed to write a Notch Metrics custom app. A custom app is a",
    "> local connector: one directory holding a manifest and a JavaScript module,",
    "> which runs on the user's own Mac against their own API key and is never",
    "> uploaded. Each number it declares becomes a widget in the MacBook notch.",
    "",
    `Canonical URL: ${SITE_URL}/docs/llms.txt`,
    `Human documentation: ${absoluteUrl("/docs")}`,
    "",
    "## What this file contains",
    "",
    "1. Every documentation page, in reading order, in full.",
    "2. The JSON Schema the manifest is validated against.",
    "3. The TypeScript interfaces the runner supplies and expects.",
    "4. A complete worked example.",
    "",
    "## Rules that are not negotiable",
    "",
    "- All network access goes through `ctx.http`. A bare `fetch` bypasses the",
    "  host allowlist, the redirect re-check and the response cap.",
    "- Every host the connector contacts is listed in `allowedHosts`. Nothing",
    "  else is reachable through `ctx.http`.",
    "- A connector is **contained, not sandboxed**. The allowlist bounds where it",
    "  can send data. It still runs as the user, with their file system.",
    "- `entry` is always `connector.mjs`.",
    "- The module has one default export, built by `createApp`.",
    "- Each metric is a `createMetric` object carrying its own `fetch`. Metrics",
    "  are not declared in the manifest.",
    "- `manifest.json` is GENERATED by `npx @notchmetrics/core build`. Never hand",
    "  write it, and never ask the user to.",
    "- `verify` is optional, and only worth writing where there is a credential.",
    "- Money is an integer in minor units with an ISO 4217 code. Never a float.",
    "",
    "## Debugging a connector that is already installed",
    "",
    "Every app writes a log. Read it before guessing:",
    "",
    "```",
    "~/Library/Application Support/NotchMetrics/logs/custom-apps/<app-id>.log",
    "```",
    "",
    "Each run appends a block naming the verb, the metrics asked for and the",
    "duration, then one line per outcome, one per HTTP call with its status,",
    "and one per `ctx.log` message.",
    "",
    "```",
    "=== 2026-10-26 16:04:11  fetch  downloads  154ms",
    "  ok downloads value=42444710 points=7",
    "  http GET api.npmjs.org 200 1051ms",
    "  log asked for react",
    "```",
    "",
    "What each line tells you:",
    "",
    "- `failed <metric> [runtime] <message>` is the error the code threw.",
    "- `[policy]` with `http ... blocked` means the host is missing from",
    "  `allowedHosts`. That is the one failure the tile cannot explain.",
    "- `[timeout]` means the whole run passed `timeoutMs`, which every metric",
    "  in that run shares.",
    "- `[bad_result]` means `fetch` returned a shape the app refused. The line",
    "  names the field.",
    "",
  ];

  // The prose, in the order the sidebar shows it.
  let currentSection = "";
  for (const doc of docs) {
    if (doc.section !== currentSection) {
      currentSection = doc.section;
      parts.push(...sectionHeading(SECTION_LABELS[doc.section]));
    }
    parts.push(
      "",
      `## ${doc.title}`,
      "",
      `URL: ${absoluteUrl(`/docs/${doc.slug}`)}`,
      "",
      doc.markdown,
      "",
    );
  }

  parts.push(
    ...sectionHeading("Manifest JSON Schema"),
    "Generated from `packages/core`. A manifest that does not validate against",
    "this is refused when the app is loaded.",
    "",
    "```json",
    MANIFEST_SCHEMA,
    "```",
    "",
    ...sectionHeading("Authoring API"),
    "`createApp` and `createMetric`, with the types an editor checks against.",
    "This is the source of the package an author imports.",
    "",
    "```ts",
    AUTHORING_API,
    "```",
    "",
    ...sectionHeading("Runtime contract"),
    "The object the runner hands to `verify` and to each metric's `fetch`.",
    "Nothing here is imported at run time, so a connector runs with no",
    "`node_modules` beside it.",
    "",
    "```ts",
    RUNTIME_CONTRACT,
    "```",
    "",
    ...sectionHeading("Example manifest"),
    "The fixture the Mac app's own contract tests decode. If a generated",
    "manifest differs structurally from this one, the generated one is wrong.",
    "",
    "```json",
    EXAMPLE_MANIFEST,
    "```",
    "",
  );

  parts.push(...sectionHeading("Example connector.mjs"), "", EXAMPLE_MODULE, "");

  return parts.join("\n");
}

/**
 * A worked module, written out here rather than read from a fixture.
 *
 * The committed fixtures are a *manifest*; there is no committed connector
 * module that is both minimal and illustrative, and the test connectors under
 * `packages/metric-runtime/test` are written to exercise the runner rather
 * than to be read. This one is checked by eye against the runtime contract
 * printed directly above it in the same file, which is the next best thing to
 * generating it.
 */
const EXAMPLE_MODULE = `\`\`\`js
// connector.mjs
import { createApp, createMetric } from "@notchmetrics/core";

// Everything about a metric in one object: what it is called, what it means,
// what the widget asks for, and the code that answers it.
const activeUsers = createMetric({
  id: "active_users",
  label: "Active users",
  unit: "count",
  series: { granularities: ["day"] },
  methodology: "Users with at least one session in the window.",

  async fetch(ctx, request) {
    const response = await ctx.http(
      \`https://api.example.com/v1/users?from=\${request.from}&to=\${request.to}\`,
      { headers: { authorization: \`Bearer \${ctx.credentials.api_key}\` } },
    );
    if (!response.ok) throw new Error(\`The API returned \${response.status}.\`);

    const body = await response.json();
    return {
      value: body.total,
      previousValue: request.comparePrevious ? body.previousTotal : null,
      points: body.daily.map((day) => ({ t: day.date, v: day.count })),
    };
  },
});

export default createApp({
  id: "example-app",
  name: "Example",
  description: "What this app reads, in a sentence.",
  allowedHosts: ["api.example.com"],
  auth: [{ key: "api_key", label: "API key", type: "secret" }],

  // Optional. An app against a public API has nothing to prove.
  async verify(ctx) {
    const response = await ctx.http("https://api.example.com/v1/account", {
      headers: { authorization: \`Bearer \${ctx.credentials.api_key}\` },
    });
    if (!response.ok) throw new Error(\`The API key was rejected (\${response.status}).\`);

    const account = await response.json();
    return { accountLabel: account.name, currency: account.currency };
  },
  metrics: [activeUsers],
});
\`\`\``;
